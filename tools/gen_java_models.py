#!/usr/bin/env python3
"""Generate the Java wire models from spec/models.yaml.

    python3 tools/gen_java_models.py           # write the sources
    python3 tools/gen_java_models.py --check   # fail if the committed sources are stale (CI)

Hand-written convenience code lives in tools/java_extra/<Name>.java and is
merged into the generated class: lines after ``// @imports``, ``// @class`` and
``// @builder`` markers go to the import list, the class body and the builder
body respectively.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from typing import Dict, List, Tuple

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "spec", "models.yaml")
EXTRA = os.path.join(ROOT, "tools", "java_extra")
PACKAGE = "io.datadynamics.ranger.client.model"
OUT = os.path.join(ROOT, "java", "ranger-sdk-model", "src", "main", "java", *PACKAGE.split("."))

HEADER = "// GENERATED by tools/gen_java_models.py from spec/models.yaml. Do not edit by hand.\n"
BASE_ACCESSORS = {"id": "getId", "guid": "getGuid", "isEnabled": "isEnabled", "version": "getVersion"}


def java_type(t: str) -> str:
    t = t.strip()
    m = re.fullmatch(r"Enum<(\w+)>", t)
    if m:
        return m.group(1)
    m = re.fullmatch(r"List<(.+)>", t)
    if m:
        return f"List<{java_type(m.group(1))}>"
    m = re.fullmatch(r"Map<\s*String\s*,\s*(.+)>", t)
    if m:
        return f"Map<String, {java_type(m.group(1))}>"
    return t


def is_enum(t: str) -> bool:
    return t.strip().startswith("Enum<")


def cap(s: str) -> str:
    return s[0].upper() + s[1:]


def getter(field: str) -> str:
    if re.match(r"is[A-Z]", field):
        return field
    return "get" + cap(field)


def setter(field: str) -> str:
    if re.match(r"is[A-Z]", field):
        return field[2].lower() + field[3:]
    return field


def read_extra(name: str) -> Dict[str, List[str]]:
    path = os.path.join(EXTRA, name)
    sections: Dict[str, List[str]] = {"imports": [], "class": [], "builder": []}
    if not os.path.exists(path):
        raise SystemExit(f"missing {path}")
    current = None
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"\s*// @(imports|class|builder)\s*$", line)
            if m:
                current = m.group(1)
                continue
            if current:
                sections[current].append(line.rstrip("\n"))
    return sections


def render(name: str, spec: Dict, base_fields: Dict[str, str]) -> str:
    fields: List[Tuple[str, str]] = []
    if spec.get("base"):
        fields += list(base_fields.items())
    fields += list((spec.get("fields") or {}).items())
    secret = spec.get("secret") or []
    extra = read_extra(spec["java_extra"]) if spec.get("java_extra") else {"imports": [], "class": [], "builder": []}

    imports = {"java.util.List", "java.util.Map"} if any(("List<" in t or "Map<" in t) for _, t in fields) else set()
    imports |= {i.strip() for i in extra["imports"] if i.strip()}
    if secret:
        imports.add("java.util.Set")
    out: List[str] = [HEADER, f"package {PACKAGE};", ""]
    for imp in sorted(i.replace("import ", "").rstrip(";") for i in imports):
        out.append(f"import {imp};")
    if imports:
        out.append("")
    implements = " implements RangerBaseObject" if spec.get("base") else ""
    out.append(f"/** Wire model of {name} (JSON fields: {', '.join(f for f, _ in fields)}). */")
    out.append(f"public final class {name} extends RangerModel{implements} {{")
    for f, t in fields:
        stored = "String" if is_enum(t) else java_type(t)
        out.append(f"    private {stored} {f};")
    out.append("")
    out.append(f"    {name}() {{")
    out.append("    }")
    out.append("")
    out.append(f"    private {name}(Builder b) {{")
    out.append("        super(b);")
    for f, t in fields:
        jt = java_type(t)
        if jt.startswith("List<"):
            out.append(f"        this.{f} = Copy.list(b.{f});")
        elif jt.startswith("Map<"):
            out.append(f"        this.{f} = Copy.map(b.{f});")
        else:
            out.append(f"        this.{f} = b.{f};")
    out.append("    }")
    for f, t in fields:
        jt = java_type(t)
        out.append("")
        override = "    @Override\n" if spec.get("base") and f in BASE_ACCESSORS else ""
        if is_enum(t):
            out.append(f"{override}    public {jt} {getter(f)}() {{")
            out.append(f"        return {f} == null ? null : {jt}.of({f});")
            out.append("    }")
            out.append("")
            out.append(f"    /** The value exactly as the server sent it (kept for values newer than this SDK). */")
            out.append(f"    public String {getter(f)}Raw() {{")
            out.append(f"        return {f};")
            out.append("    }")
        elif jt.startswith("List<"):
            out.append(f"{override}    public {jt} {getter(f)}() {{")
            out.append(f"        return Copy.view({f});")
            out.append("    }")
        elif jt.startswith("Map<"):
            out.append(f"{override}    public {jt} {getter(f)}() {{")
            out.append(f"        return Copy.view({f});")
            out.append("    }")
        else:
            out.append(f"{override}    public {jt} {getter(f)}() {{")
            out.append(f"        return {f};")
            out.append("    }")
    if secret:
        out.append("")
        out.append("    @Override")
        out.append("    protected Set<String> secretFields() {")
        out.append("        return Set.of(" + ", ".join(f'"{s}"' for s in secret) + ");")
        out.append("    }")
    out.append("")
    out.append("    public static Builder builder() {")
    out.append("        return new Builder();")
    out.append("    }")
    out.append("")
    out.append("    public Builder toBuilder() {")
    out.append("        Builder b = new Builder();")
    out.append("        b.copyExtra(this);")
    for f, t in fields:
        jt = java_type(t)
        if jt.startswith("List<"):
            out.append(f"        b.{f} = Copy.mutableList({f});")
        elif jt.startswith("Map<"):
            out.append(f"        b.{f} = Copy.mutableMap({f});")
        else:
            out.append(f"        b.{f} = {f};")
    out.append("        return b;")
    out.append("    }")
    if extra["class"]:
        out.append("")
        out.extend(extra["class"])
    out.append("")
    out.append(f"    /** Builder for {{@link {name}}}. */")
    out.append(f"    public static final class Builder extends RangerModel.Builder<{name}, Builder> {{")
    for f, t in fields:
        stored = "String" if is_enum(t) else java_type(t)
        out.append(f"        private {stored} {f};")
    out.append("")
    out.append("        Builder() {")
    out.append("        }")
    for f, t in fields:
        jt = java_type(t)
        out.append("")
        if is_enum(t):
            out.append(f"        public Builder {setter(f)}({jt} {f}) {{")
            out.append(f"            this.{f} = {f} == null ? null : {f}.name();")
        elif jt.startswith("List<"):
            out.append(f"        public Builder {setter(f)}({jt} {f}) {{")
            out.append(f"            this.{f} = Copy.mutableList({f});")
        elif jt.startswith("Map<"):
            out.append(f"        public Builder {setter(f)}({jt} {f}) {{")
            out.append(f"            this.{f} = Copy.mutableMap({f});")
        else:
            out.append(f"        public Builder {setter(f)}({jt} {f}) {{")
            out.append(f"            this.{f} = {f};")
        out.append("            return this;")
        out.append("        }")
    if extra["builder"]:
        out.append("")
        out.extend(extra["builder"])
    out.append("")
    out.append("        @Override")
    out.append(f"        public {name} build() {{")
    out.append(f"            return new {name}(this);")
    out.append("        }")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    with open(SPEC, encoding="utf-8") as fh:
        spec = yaml.safe_load(fh)
    os.makedirs(OUT, exist_ok=True)
    stale = []
    for name, m in spec["models"].items():
        src = render(name, m, spec["base_fields"])
        path = os.path.join(OUT, f"{name}.java")
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != src:
            stale.append(path)
            if not args.check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(src)
    if args.check and stale:
        print("stale generated models (run tools/gen_java_models.py):", *stale, sep="\n  ")
        return 1
    print(f"{len(spec['models'])} models, {len(stale)} {'stale' if args.check else 'written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
